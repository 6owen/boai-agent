class RuntimeStartupOwnedError extends Error {}

function startRuntime() {
  if (ready) return ready
  ready = browserConnectionDrain.then(async () => {
    const attached = await findAttachedRuntime(dataPath, app.getVersion(), desktopHostId)
    try { await connectRuntime(attached) }
    catch (error) {
      if (!(error instanceof RuntimeStartupOwnedError) || quitting) throw error
      // connectRuntime reports ownership rejection only after the uninitialized worker exits.
      const winner = await waitForAttachedRuntime(dataPath, app.getVersion(), desktopHostId, { stopping: () => quitting })
      await connectRuntime(winner)
    }
  }).catch(error => { diagnostics.record('runtime-start-failed', diagnosticError(error)); if (!runtime) ready = null; throw error })
  return ready
}

function connectRuntime(attached: AttachedRuntime | null) {
  return new Promise<void>((resolveReady, rejectReady) => {
    let workerReady = false, ownershipRejected = false
    let childPid: number | undefined
    // Only carry platform essentials into the worker. Model credentials arrive through the vault.
    const env = Object.fromEntries(Object.entries(process.env).filter(([key]) => /^(PATH|HOME|USER|SHELL|LANG|LC_.*|TMPDIR|TEMP|TMP|SystemRoot|APPDATA|LOCALAPPDATA|USERPROFILE)$/i.test(key)))
    const child = attached ?? utilityProcess.fork(join(__dirname, '../runtime/worker.mjs'), [dataPath], {
      serviceName: 'BoAI Agent Runtime', stdio: 'pipe', env: { ...env, BOAI_NATIVE_PROCESS_GUARD: join(__dirname,'../native/boai-process-guard').replace('app.asar/','app.asar.unpacked/') },
    })
    runtime = child
    if (child instanceof AttachedRuntime) diagnostics.record('runtime-start', { serverId: child.serverId })
    else child.once('spawn', () => { childPid = child.pid; diagnostics.record('runtime-start', { pid: childPid }) })
    const timer = setTimeout(() => { rejectReady(new Error('本地运行服务启动超时。')); child.kill() }, 90_000)
    child.on('message', async (message) => {
      if (runtime !== child) return
      if (message?.type === 'owner-busy' && !workerReady && !(child instanceof AttachedRuntime)) { ownershipRejected = true; child.kill(); return }
      if (message?.type === 'ready') {
        if (!(child instanceof AttachedRuntime)) childPid ??= child.pid
        diagnostics.record('runtime-ready', { pid: childPid, ...(child instanceof AttachedRuntime ? { serverId: child.serverId } : {}) })
        workerReady = true
        clearTimeout(timer)
        try {
          if (!(child instanceof AttachedRuntime) && !cli && !quitting) cli = await openDesktopCli(dataPath, app.getVersion(), { runAccess: async input => {
            if (quitting) throw new CliError('SERVER_BUSY', '应用正在退出')
            const reply = await requestCurrentRuntime(child, '__runCliAccess', input) as { ok: boolean; result?: unknown; code: ErrorCode; message: string }
            if (!reply.ok) throw new CliError(reply.code, reply.message)
            return reply.result
          }, request: async (method, input) => {
            if (quitting) throw new Error('应用正在退出，不再受理 CLI 请求')
            return await requestRuntime(method, input) as never
          } })
          resolveReady(); flushAutomationNotifications()
        } catch (error) { rejectReady(error) }
        return
      }
      if (message?.type === 'attach-error') { clearTimeout(timer); rejectReady(new Error(message.error)); return }
      if (message?.type === 'stopped') return
      if (message?.type === 'response') {
        const response = message.response as RpcResponse
        const request = pending.get(response.id)
        if (!request) return
        clearTimeout(request.timer)
        pending.delete(response.id)
        if (response.error) request.reject(new Error(response.error))
        else request.resolve(response.result)
      } else if (message?.type === 'event') { if (message.event?.type === 'automation:notice') flushAutomationNotifications(); else sendEvent(message.event) }

      else if (message?.type === 'application-host') {
        try {
          if (!isApplicationHostMethod(message.method)) throw new Error('未公开的桌面设置方法')
          const result = await applicationHostRequest(message.method, message.input)
          if (runtime === child) child.postMessage({ type: 'application-host-result', id: message.id, result })
        } catch (error) { if (runtime === child) child.postMessage({ type: 'application-host-result', id: message.id, error: error instanceof Error ? error.message : '桌面设置结果未知' }) }
      }
      else if (message?.type === 'browser-host') {
        try {
          if (quitting && (message.method === 'acquire' || message.method === 'executeSingle')) throw new Error('应用正在退出，浏览器不再受理新动作。')
          const result = await handleBrowserHostRequest(child, message.method, message.input)
          if (runtime === child) child.postMessage({ type: 'browser-host-result', id: message.id, result })
        } catch (error) {
          if (runtime === child) child.postMessage({ type: 'browser-host-result', id: message.id, error: error instanceof Error ? error.message : '浏览器操作结果未知，请核对原动作。' })
        }
      }
      else if (message?.type === 'secret') {
        try {
          if (typeof message.key !== 'string' || message.key.length > 200) throw new Error('无效凭据标识。')
          let value: string | boolean | undefined
          if (message.operation === 'has') value = await vault.has(message.key)
          else if (message.operation === 'get') value = await vault.get(message.key)
          else if (message.operation === 'set' && typeof message.value === 'string') await vault.set(message.key, message.value)
          else if (message.operation === 'delete') await vault.delete(message.key)
          else throw new Error('无效凭据操作。')
          child.postMessage({ type: 'secret-result', id: message.id, value })
        } catch (error) {
          child.postMessage({ type: 'secret-result', id: message.id, error: error instanceof Error ? error.message : '凭据操作失败。' })
        }
      }
    })
    child.stderr?.on('data', (chunk) => { if (!app.isPackaged) process.stderr.write(chunk) })
    child.stdout?.on('data', (chunk) => { if (!app.isPackaged) process.stdout.write(chunk) })
    child.on('exit', (code) => {
      clearTimeout(timer)
      // Electron clears child.pid before exit; preserve the PID observed at spawn/ready.
      diagnostics.record('runtime-exit', { pid: childPid, ...(typeof code === 'number' ? { exitCode: code } : {}), ...(child instanceof AttachedRuntime ? { reason: 'disconnected', serverId: child.serverId } : {}) })
      if (runtime !== child) return
      if (ownershipRejected && !workerReady) { runtime = null; rejectReady(new RuntimeStartupOwnedError('原运行服务已取得所有权')); return }
      // Replacing the connection cannot issue a new lease until old actions really exit.
      browserConnectionDrain = browsers.disconnectAll().catch(error => { sendEvent({ type: 'runtime-error', error: String(error) }); throw error })
      void browserConnectionDrain.catch(() => {})
      runtime = null
      ready = null
      const error = new Error(child instanceof AttachedRuntime ? '独立服务连接已断开，请核对原请求；不会自动重发。' : `本地运行服务已退出（${code}），下一次操作会重新启动。`)
      rejectReady(error)
      for (const request of pending.values()) { clearTimeout(request.timer); request.reject(error) }
      pending.clear()
      if (!quitting) sendEvent({ type: 'runtime-error', error: error.message })
    })
    if (child instanceof AttachedRuntime) void child.start()
  })
}

async function handleBrowserHostRequest(child: RuntimeHandle, method: keyof BrowserHostMethods, input: unknown): Promise<unknown> {
  await browserConnectionDrain
  if (runtime !== child) throw new Error('浏览器原运行连接已失效。')
  switch (method) {
    case 'manualOpen': return browsers.manualOpen(input as BrowserHostMethods['manualOpen']['input'])
    case 'currentLease': return browsers.currentLease()
    case 'acquire': return browsers.acquire(input as BrowserLease)
    case 'reference': return browsers.reference(input as {instanceId?:string;pageVersion?:string})
    case 'inspect': return browsers.inspect(input as BrowserLease)
    case 'resumeSnapshot': return browsers.resumeSnapshot(input as BrowserLease)
    case 'executeSingle': {
      const value = input as BrowserHostMethods['executeSingle']['input']
      return browsers.executeSingle(value, async () => {
        if (runtime !== child || quitting) throw new Error('浏览器动作尚未开始，原连接已经退出。')
        await requestRuntime('__startBrowserAction', { actionId: value.actionId, generation: value.lease.generation, runId: value.lease.runId, workId: value.lease.workId })
      })
    }
    case 'lookup': return browsers.lookup(input as BrowserHostMethods['lookup']['input'])
    case 'drain': await browsers.drain(input as BrowserLease); return { drained: true }
    case 'clearScope': await browsers.clearScope(input as BrowserHostMethods['clearScope']['input']); return { cleared: true }
    case 'list': return browsers.list()
    case 'userControl': return browsers.userControl(input as BrowserHostMethods['userControl']['input'])
    case 'disconnect': return browsers.disconnectAll()
    default: throw new Error('未知浏览器宿主操作。')
  }
}

async function requestRuntime(method: string, input?: unknown, waitForCompletion = false) {
  await startRuntime()
  return requestCurrentRuntime(runtime!, method, input, waitForCompletion)
}

function requestCurrentRuntime(child: RuntimeHandle, method: string, input?: unknown, waitForCompletion = false) {
  if (!child || runtime !== child) return Promise.reject(new Error('原运行服务连接已失效。'))
  const id = randomUUID()
  return new Promise<unknown>((resolveRequest, reject) => {
    // Temporary input files must remain until the importer responds or its worker really exits.
    const timer = waitForCompletion ? undefined : setTimeout(() => { diagnostics.record('request-timeout', diagnosticRequest(method, id, input)); pending.delete(id); reject(new Error('操作超时，请查看任务状态。')) }, 120_000)
    pending.set(id, { resolve: resolveRequest, reject, timer })
    try { child.postMessage({ type: 'request', request: { id, method, input }, waitForCompletion }) }
    catch (error) { clearTimeout(timer); pending.delete(id); reject(error) }
  }).catch(error => { diagnostics.record('request-failed', { ...diagnosticRequest(method, id, input), ...diagnosticError(error) }); throw error })
}

function inside(root: string, target: string) {
  const path = relative(root, target)
  return path === '' || (!path.startsWith('..') && !isAbsolute(path))
}

async function openResource(input: unknown) {
  const value = z.object({ path: z.string().min(1), action: z.enum(['open', 'reveal']).optional() }).strict().parse(input)
  const target = await realpath(value.path)
  const snapshot = await requestRuntime('snapshot') as Snapshot
  const roots = await Promise.all([...snapshot.conversations.map((c) => c.workspacePath), ...snapshot.resources.map((r) => r.path), ...snapshot.agents.map(a => join(dataPath, 'agents', a.id, 'workspace')), ...snapshot.agents.map(a => join(dataPath,'external-workspaces',a.id))].map((p) => realpath(p).catch(() => '')))
  const info = await stat(target)
  const dataRoot = await realpath(dataPath)
  if (!(info.isDirectory() && (target === dataRoot || target === join(dataRoot, 'activity-records'))) && !roots.some((root) => root && inside(root, target))) throw new Error('只能打开当前工作区或已导入的资源。')
  await openLocalResource(shell, target, value.action)
}

